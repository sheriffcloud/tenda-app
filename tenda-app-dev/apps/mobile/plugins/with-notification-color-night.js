/**
 * Expo config plugin: gives the Android notification tint a dark-mode value.
 *
 * `expo-notifications`' own `color` option writes ONE colour — resource
 * `notification_icon_color` in `values/colors.xml` — and the manifest points
 * `com.google.firebase.messaging.default_notification_color` and
 * `expo.modules.notifications.default_notification_color` at
 * `@color/notification_icon_color`. Because those are resource references,
 * Android resolves them per configuration, so a `values-night` override is
 * picked up automatically. That is the whole mechanism this plugin uses.
 *
 * WHY it is needed: that colour tints the small icon and the app-name label
 * inside the notification shade, and the shade follows the SYSTEM theme, not
 * ours. `brand.primary` is split by ground for exactly this reason — #2E5BD6
 * reads on a light ground (5.86:1) and #5E87E8 on a dark one (4.79:1), and no
 * single value can clear 4.5:1 against both #FFFFFF and #1F1F1F: it would need
 * a relative luminance <= 0.183 and >= 0.237 at the same time. So the day value
 * stays in app.config.ts and the night value lives here.
 *
 * Hand-editing `android/res` is not an option — that tree is gitignored and
 * regenerated by prebuild. A plugin re-runs every prebuild, so it survives
 * `--clean`.
 */
const { withAndroidColors, withAndroidColorsNight, AndroidConfig } = require('@expo/config-plugins')

/**
 * Must match `NOTIFICATION_ICON_COLOR` in
 * expo-notifications/plugin/build/withNotificationsAndroid.js. It is another
 * package's internal resource name, so `assertDayColorExists` below fails the
 * prebuild if it ever moves rather than letting us write a night override that
 * nothing reads.
 */
const RESOURCE = 'notification_icon_color'

/** Dark-theme `brand.primary`, kept in step with theme/tokens.ts (~line 290). */
const NIGHT_COLOR = '#5E87E8'

/**
 * Read-only guard: asserts expo-notifications really did write the resource we
 * are about to shadow, so a rename upstream fails the build instead of leaving
 * a values-night override that nothing reads.
 *
 * Registered as a plain colours mod so it sees `values/colors.xml` AFTER
 * expo-notifications has written to it. That requires this plugin to be listed
 * BEFORE 'expo-notifications' in app.config.ts, because config mods run in
 * REVERSE registration order — `withMod`'s `interceptingMod` hands each action
 * the previously-registered mod as `nextMod`, so a later entry runs earlier.
 * Getting this backwards is not silent: the guard below fires on a clean
 * prebuild, which is how the ordering was established.
 */
function assertDayColorExists(config) {
  return withAndroidColors(config, (mod) => {
    const colors = AndroidConfig.Colors.getColorsAsObject(mod.modResults)
    if (!colors || !(RESOURCE in colors)) {
      throw new Error(
        `[with-notification-color-night] expected the '${RESOURCE}' colour in values/colors.xml, ` +
          `written by the expo-notifications plugin's \`color\` option, but it is not there. ` +
          `Either that plugin stopped running before this one, or it renamed the resource — ` +
          `in both cases a values-night override would be silently dead, so this fails instead.`,
      )
    }
    return mod
  })
}

function setNightColor(config) {
  return withAndroidColorsNight(config, (mod) => {
    mod.modResults = AndroidConfig.Colors.assignColorValue(mod.modResults, {
      name: RESOURCE,
      value: NIGHT_COLOR,
    })
    return mod
  })
}

module.exports = function withNotificationColorNight(config) {
  config = assertDayColorExists(config)
  config = setNightColor(config)
  return config
}
